#!/usr/bin/env node
// The Codex app-server protocol types ORCA builds against (#1156), one checked-in copy per
// pinned Codex version under packages/agents/src/codex-protocol/<version>/.
//
//   node tools/codex-protocol.mjs generate --codex <path to codex>
//   node tools/codex-protocol.mjs check --codex <path to codex>
//
// `generate` runs the given Codex's own `codex app-server generate-ts` (stable surface only,
// no --experimental) in an empty CODEX_HOME, so nothing of the machine's Codex configuration
// reaches the output, then writes the result for the version that Codex reports:
//
// - every generated .ts file, with one change: a relative import gets the `.js` extension
//   ORCA's NodeNext resolution needs (`from "./X"` -> `from "./X.js"`, `"./v2"` -> `"./v2/index.js"`);
// - manifest.ts, the method names of each direction, read from the generated unions;
// - SHA256SUMS, one line per file, so a hand edit is caught without a Codex at hand.
//
// `check` generates into a temporary directory and compares it byte for byte with the
// checked-in copy, exiting 1 with every difference listed. The Codex app-server protocol
// workflow runs it against the pinned Codex, so a pin whose types drifted fails.
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const PROTOCOL_ROOT = join(repoRoot, "packages", "agents", "src", "codex-protocol");

/** Every file under `dir`, as `/`-separated paths relative to it, sorted. */
export function listFiles(dir) {
  const out = [];
  const walk = (d) => {
    for (const name of readdirSync(d).sort()) {
      const full = join(d, name);
      if (statSync(full).isDirectory()) walk(full);
      else out.push(relative(dir, full).split(sep).join("/"));
    }
  };
  walk(dir);
  return out.sort();
}

/** The `.js` extension NodeNext needs on a relative import; a directory import names its index. */
export function withExtensions(source, fileDir) {
  return source.replace(/(from\s+")(\.{1,2}\/[^"]*)(")/g, (whole, open, spec, close) => {
    if (spec.endsWith(".js")) return whole;
    const target = resolve(fileDir, spec);
    if (existsSync(target) && statSync(target).isDirectory()) return `${open}${spec}/index.js${close}`;
    return `${open}${spec}.js${close}`;
  });
}

/** The `method` literals of one generated union, in file order, without repeats. */
export function methodsOf(source) {
  return [...new Set([...source.matchAll(/"method": "([^"]+)"/g)].map((m) => m[1]))];
}

const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

/** The Codex version a binary reports (`codex-cli 0.171.0`). */
export function codexVersion(codex) {
  const r = spawnSync(codex, ["--version"], { encoding: "utf8" });
  const m = /^codex-cli (\d+\.\d+\.\d+)\s*$/.exec(r.stdout ?? "");
  if (r.status !== 0 || !m)
    throw new Error(`${codex} --version did not answer "codex-cli <version>": ${r.stdout}${r.stderr}`);
  return m[1];
}

/** Generate the checked-in form of `codex`'s protocol into `out` (created, must not exist). */
export function generate(codex, out) {
  const version = codexVersion(codex);
  const home = mkdtempSync(join(tmpdir(), "orca-codex-home-"));
  const raw = mkdtempSync(join(tmpdir(), "orca-codex-ts-"));
  try {
    const r = spawnSync(codex, ["app-server", "generate-ts", "--out", raw], {
      encoding: "utf8",
      env: { PATH: process.env.PATH ?? "", HOME: home, CODEX_HOME: home },
    });
    if (r.status !== 0) throw new Error(`codex app-server generate-ts failed (${r.status}): ${r.stderr}`);
    mkdirSync(out, { recursive: true });
    for (const file of listFiles(raw)) {
      if (!file.endsWith(".ts")) throw new Error(`unexpected generated file ${file}`);
      const from = join(raw, file);
      const to = join(out, file);
      mkdirSync(dirname(to), { recursive: true });
      writeFileSync(to, withExtensions(readFileSync(from, "utf8"), dirname(from)));
    }
    const read = (name) => readFileSync(join(raw, name), "utf8");
    const list = (name, values) =>
      `/** ${name}: the methods of the generated union, in its order. */\nexport const ${name} = ${JSON.stringify(values, null, 2)} as const;\n`;
    writeFileSync(
      join(out, "manifest.ts"),
      `// GENERATED by tools/codex-protocol.mjs from codex ${version}'s \`app-server generate-ts\`. Do not edit.\n\n` +
        `/** The Codex version these types were generated from. */\nexport const CODEX_PROTOCOL_VERSION = ${JSON.stringify(version)};\n\n` +
        list("CLIENT_REQUEST_METHODS", methodsOf(read("ClientRequest.ts"))) +
        "\n" +
        list("CLIENT_NOTIFICATION_METHODS", methodsOf(read("ClientNotification.ts"))) +
        "\n" +
        list("SERVER_REQUEST_METHODS", methodsOf(read("ServerRequest.ts"))) +
        "\n" +
        list("SERVER_NOTIFICATION_METHODS", methodsOf(read("ServerNotification.ts"))),
    );
    const sums = listFiles(out)
      .map((file) => `${sha256(readFileSync(join(out, file)))}  ${file}`)
      .join("\n");
    writeFileSync(join(out, "SHA256SUMS"), sums + "\n");
    return version;
  } finally {
    rmSync(home, { recursive: true, force: true });
    rmSync(raw, { recursive: true, force: true });
  }
}

/** Differences between two trees, one line each; empty when they are byte for byte the same. */
export function compareTrees(expected, actual) {
  const a = existsSync(expected) ? listFiles(expected) : [];
  const b = existsSync(actual) ? listFiles(actual) : [];
  const diffs = [];
  for (const f of a) if (!b.includes(f)) diffs.push(`missing from generated output: ${f}`);
  for (const f of b) if (!a.includes(f)) diffs.push(`not checked in: ${f}`);
  for (const f of a)
    if (b.includes(f) && !readFileSync(join(expected, f)).equals(readFileSync(join(actual, f))))
      diffs.push(`differs: ${f}`);
  return diffs;
}

/** Hand edits: files whose bytes do not match the checked-in SHA256SUMS, or that it does not list. */
export function verifySums(dir) {
  const listed = new Map(
    readFileSync(join(dir, "SHA256SUMS"), "utf8")
      .split("\n")
      .filter(Boolean)
      .map((line) => {
        const m = /^([0-9a-f]{64}) {2}(.+)$/.exec(line);
        if (!m) throw new Error(`bad SHA256SUMS line: ${line}`);
        return [m[2], m[1]];
      }),
  );
  const problems = [];
  const present = listFiles(dir).filter((f) => f !== "SHA256SUMS");
  for (const f of present) {
    const want = listed.get(f);
    if (want === undefined) problems.push(`not in SHA256SUMS: ${f}`);
    else if (want !== sha256(readFileSync(join(dir, f)))) problems.push(`changed since generation: ${f}`);
  }
  for (const f of listed.keys()) if (!present.includes(f)) problems.push(`listed but missing: ${f}`);
  return problems;
}

function main(argv) {
  const [command, flag, codex] = argv;
  if (!["generate", "check"].includes(command) || flag !== "--codex" || !codex) {
    console.error("usage: node tools/codex-protocol.mjs generate|check --codex <path to codex>");
    return 2;
  }
  const version = codexVersion(codex);
  const target = join(PROTOCOL_ROOT, version);
  if (command === "generate") {
    rmSync(target, { recursive: true, force: true });
    generate(codex, target);
    process.stdout.write(`wrote ${relative(repoRoot, target)}\n`);
    return 0;
  }
  const scratch = mkdtempSync(join(tmpdir(), "orca-codex-protocol-"));
  try {
    generate(codex, join(scratch, version));
    const diffs = compareTrees(target, join(scratch, version));
    if (diffs.length === 0) {
      process.stdout.write(`${relative(repoRoot, target)} matches codex ${version}'s generated protocol\n`);
      return 0;
    }
    console.error(`${relative(repoRoot, target)} has drifted from codex ${version}'s generated protocol:`);
    for (const d of diffs) console.error(`  ${d}`);
    console.error(`Regenerate it with: node tools/codex-protocol.mjs generate --codex ${codex}`);
    return 1;
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  process.exitCode = main(process.argv.slice(2));
