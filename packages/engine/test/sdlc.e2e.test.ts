/**
 * End-to-end: the shipped ai-sdlc workflow driven by the scripted ACP agent
 * (a real child process speaking ACP over stdio). Exercises artifact hand-off,
 * decision routing on front matter, the build/test retry loop, review rounds,
 * follow-up prompting for missing artifacts, and the auto-approving gate.
 */
import { rm } from "node:fs/promises";
import { afterAll, describe, expect, it } from "vitest";
import { harness } from "./helpers.js";
import { RequestSchema, WorkItemSchema } from "@orca/core";

const dirs: string[] = [];
afterAll(async () => {
  for (const d of dirs) await rm(d, { recursive: true, force: true });
});

const workItem = {
  id: "wi_1",
  requestId: "req_1",
  slug: "auth-api",
  title: "Auth API",
  description: "Add login endpoint",
  kind: "task",
  acceptanceCriteria: ["POST /login returns a token"],
  dependsOn: [],
  status: "pending",
  createdAt: "t",
  updatedAt: "t",
};

describe("ai-sdlc workflow (e2e with scripted ACP agent)", () => {
  it("runs plan -> design -> build -> test -> review -> deploy and passes artifacts along", async () => {
    const h = await harness({
      kinds: {
        spec: [
          {
            data: { status: "ready", risk: "low" },
            body: "# Spec\n\nRequirements: R1 login endpoint. Design: token service. Test strategy: unit + integration tests.",
          },
        ],
        implementation: [{ data: { status: "done", branch: "orca/auth-api" }, body: "Implemented login." }],
        "test-report": [
          { data: { status: "done", passed: false, failures: 1 }, body: "1 failing test" },
          { data: { status: "done", passed: true, failures: 0 }, body: "all green" },
        ],
        review: [
          { data: { status: "done", verdict: "changes-requested" }, body: "Please add rate limiting." },
          { data: { status: "done", verdict: "approve" }, body: "LGTM" },
        ],
      },
    });
    dirs.push(h.dir);
    await h.orchestrator.stores.requests.put(
      RequestSchema.parse({ id: workItem.requestId, title: "Auth request", body: "", createdAt: "t", updatedAt: "t" }),
    );
    await h.orchestrator.stores.workItems.put(WorkItemSchema.parse(workItem));
    const state = await h.orchestrator.startAndRun({ workflowId: "ai-sdlc", workItemId: "wi_1", vars: { workItem } });

    expect(state.run.status, JSON.stringify(state.run.error)).toBe("completed");
    expect(state.run.outcome).toBe("success");
    const path = state.stepOrder.map((id) => state.steps[id]!.nodeId);
    expect(path).toEqual([
      "start",
      "plan",
      "design",
      "spec-gate",
      "await-deps",
      "bump-build",
      "build",
      "test",
      "tests-passed", // tests fail -> retry build
      "bump-build",
      "build",
      "test",
      "tests-passed", // tests pass
      "bump-review",
      "review",
      "review-verdict", // changes requested -> build again
      "bump-build",
      "build",
      "test",
      "tests-passed",
      "bump-review",
      "review",
      "review-verdict", // approved
      "deploy",
      "delivery-status",
      "done",
    ]);
    expect(state.run.vars).toMatchObject({ buildAttempt: 3, reviewRound: 2 });

    const arts = Object.values(state.artifacts);
    const byName = (n: string) => arts.filter((a) => a.name === n).sort((a, b) => a.version - b.version);
    expect(byName("testReport").map((a) => a.data.passed)).toEqual([false, true, true]);
    expect(byName("review").map((a) => a.data.verdict)).toEqual(["changes-requested", "approve"]);
    expect(byName("implementation").map((a) => a.version)).toEqual([1, 2, 3]);
    expect(byName("deployReport")).toHaveLength(1);
    const spec = byName("spec")[0]!;
    expect(spec.path?.replaceAll("\\", "/")).toBe(
      `${h.dir.replaceAll("\\", "/")}/.orca/work/auth-api/.orca-attempts/${state.run.id}/${spec.producedBy.stepRunId}/spec.md`,
    );

    // The prompt for the second build contained the failing test report; the third contained the review.
    const prompts = await h.prompts();
    const builds = prompts.filter((p) => p.text.includes("You are the **build agent**"));
    expect(builds).toHaveLength(3);
    expect(builds[0]!.text).not.toContain("Previous test report");
    expect(builds[1]!.text).toContain("Previous test report (attempt 2)");
    expect(builds[1]!.text).toContain("1 failing test");
    expect(builds[2]!.text).toContain("Review feedback (round 1)");
    expect(builds[2]!.text).toContain("rate limiting");
    // Design prompt embeds the intent artifact produced by the plan step.
    const design = prompts.find((p) => p.text.includes("You are the **design agent**"))!;
    expect(design.text).toContain("Generated by the scripted agent");
    // Every prompt carries the machine-readable deliverables block with absolute paths.
    for (const p of prompts) expect(p.text).toContain("<!-- orca:deliverables");

    // Event log tells the whole story.
    const events = await h.orchestrator.events(state.run.id);
    const types = new Set(events.map((e) => e.type));
    for (const t of [
      "run.created",
      "run.started",
      "step.scheduled",
      "agent.session.opened",
      "agent.turn.started",
      "agent.update",
      "agent.turn.completed",
      "artifact.recorded",
      "decision.resolved",
      "vars.set",
      "run.completed",
    ])
      expect(types.has(t as never), t).toBe(true);
    const gate = events.find((e) => e.type === "decision.resolved" && e.payload.source === "gate:auto");
    expect(gate).toBeDefined();
  }, 60_000);

  it("re-prompts when a required artifact is missing, then fails the run when the budget is exhausted", async () => {
    const h = await harness({
      kinds: {
        spec: [
          {
            data: { status: "ready", risk: "low" },
            body: "# Spec\n\nEnough words to satisfy the minimum body length requirement of the design step.",
          },
        ],
        // build never delivers implementation.md
        implementation: [{ skip: true }],
      },
    });
    dirs.push(h.dir);
    const state = await h.orchestrator.startAndRun({ workflowId: "ai-sdlc", vars: { workItem } });
    expect(state.run.status).toBe("failed");
    expect(state.run.error?.code).toBe("ARTIFACT_MISSING");
    const buildSteps = state.stepOrder.map((id) => state.steps[id]!).filter((s) => s.nodeId === "build");
    expect(buildSteps.map((s) => s.attempt)).toEqual([1, 2]); // completion.maxAttempts: 2
    const prompts = await h.prompts();
    const followUps = prompts.filter((p) => p.text.includes("deliverables are missing or invalid"));
    expect(followUps.length).toBe(4); // 2 follow-ups per attempt (maxFollowUps: 2)
  }, 60_000);

  it("routes high-risk specs to the human gate and honours a rejection", async () => {
    const h = await harness(
      {
        kinds: {
          spec: [
            {
              data: { status: "ready", risk: "high" },
              body: "# Risky spec\n\nA sufficiently long body for the validation rules configured in the workflow.",
            },
          ],
        },
      },
      { humanInput: { ask: async (q) => (q.question.includes("risk: high") ? "reject" : "approve") } },
    );
    dirs.push(h.dir);
    const state = await h.orchestrator.startAndRun({ workflowId: "ai-sdlc", vars: { workItem } });
    expect(state.run.status).toBe("completed");
    expect(state.run.outcome).toBe("failure");
    expect(state.stepOrder.map((id) => state.steps[id]!.nodeId).slice(-2)).toEqual(["spec-gate", "rejected"]);
    expect(Object.values(state.humanInputs).map((h) => h.answer)).toEqual(["reject"]);
  }, 60_000);
});
