/**
 * Side-car mode: reading a Kepler task directory (worktrees + task context) and
 * picking the worktree a run should work in.
 */
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterAll, describe, expect, it } from "vitest";
import type { WorkItem } from "@orca/core";
import type { ProvisionInput } from "@orca/engine";
import { inspectKeplerTask, KeplerTaskWorkspaceProvider } from "@orca/integrations";

const dirs: string[] = [];
afterAll(async () => {
  for (const d of dirs) await rm(d, { recursive: true, force: true });
});

/** A task dir as Kepler lays it out: a worktree per repo (each with a .git file) plus context markdown. */
async function task(opts: { worktrees?: string[]; files?: Record<string, string>; parent?: string } = {}): Promise<string> {
  const dir = await mkdtemp(join(opts.parent ?? tmpdir(), "orca-kepler-"));
  if (!opts.parent) dirs.push(dir);
  for (const name of opts.worktrees ?? []) {
    await mkdir(join(dir, name), { recursive: true });
    await writeFile(join(dir, name, ".git"), "gitdir: /repos/x\n", "utf8");
  }
  for (const [name, text] of Object.entries(opts.files ?? {})) await writeFile(join(dir, name), text, "utf8");
  return dir;
}

const input = (over: Partial<ProvisionInput> = {}): ProvisionInput => ({ runId: "run_1", workflowId: "ai-sdlc", ...over });
const workItem = (repo?: string) => ({ id: "wi_1", slug: "x", title: "X", ...(repo ? { repo } : {}) }) as WorkItem;

describe("inspectKeplerTask", () => {
  it("finds the worktrees and reads the task title and body from AGENTS.md", async () => {
    const dir = await task({
      worktrees: ["api", "web"],
      files: { "AGENTS.md": "<!-- generated by Kepler -->\n# Task: Ship login\n\nUsers must log in.\n", "notes.md": "ignored" },
    });
    await mkdir(join(dir, "scratch"), { recursive: true }); // a directory that is not a worktree
    await mkdir(join(dir, ".hidden"), { recursive: true }); // dotted dirs are skipped

    const info = await inspectKeplerTask(dir);
    expect(info.worktrees.map((w) => w.name).sort()).toEqual(["api", "web"]);
    expect(info.worktrees[0]!.path).toBe(join(dir, info.worktrees[0]!.name));
    expect(info.title).toBe("Ship login");
    expect(info.body).toBe("Users must log in.");
    expect(info.taskDir).toBe(dir);
  });

  it("falls back to CLAUDE.md when there is no AGENTS.md", async () => {
    const dir = await task({ files: { "CLAUDE.md": "# Task: From Claude\n\nBody.\n" } });
    expect(await inspectKeplerTask(dir)).toMatchObject({ title: "From Claude", body: "Body." });
  });

  it("leaves the title undefined when the context file has no task heading", async () => {
    const dir = await task({ files: { "AGENTS.md": "Just some notes.\n" } });
    expect(await inspectKeplerTask(dir)).toMatchObject({ title: undefined, body: "Just some notes." });
  });

  it("reports an empty task rather than throwing when the directory does not exist", async () => {
    expect(await inspectKeplerTask(join(tmpdir(), "orca-kepler-does-not-exist"))).toMatchObject({ worktrees: [], title: undefined, body: "", taskId: undefined });
  });

  it("recovers the task id from a Kepler task path", async () => {
    const root = await mkdtemp(join(tmpdir(), "orca-kepler-root-"));
    dirs.push(root);
    const tasksDir = join(root, "tasks", "0f8f1e2a-1111-4222-8333-444455556666");
    await mkdir(tasksDir, { recursive: true });
    expect((await inspectKeplerTask(tasksDir)).taskId).toBe("0f8f1e2a-1111-4222-8333-444455556666");
  });
});

describe("KeplerTaskWorkspaceProvider", () => {
  it("picks the worktree the work item names, by name or by path", async () => {
    const dir = await task({ worktrees: ["api", "web"] });
    const provider = new KeplerTaskWorkspaceProvider({ taskDir: dir, hostId: "box" });

    expect(await provider.provision(input({ workItem: workItem("web") }))).toEqual({ hostId: "box", cwd: join(dir, "web"), repo: "web", provider: "kepler" });
    expect(await provider.provision(input({ workItem: workItem(join(dir, "api")) }))).toMatchObject({ cwd: join(dir, "api"), repo: "api" });
  });

  it("keeps a child run in its parent's worktree", async () => {
    const dir = await task({ worktrees: ["api", "web"] });
    const provider = new KeplerTaskWorkspaceProvider({ taskDir: dir });
    const parent = { hostId: "local", cwd: join(dir, "web") };
    expect(await provider.provision(input({ parent }))).toMatchObject({ cwd: join(dir, "web"), repo: "web" });
  });

  it("falls back to the first worktree, defaulting the host to local", async () => {
    const dir = await task({ worktrees: ["only"] });
    const provider = new KeplerTaskWorkspaceProvider({ taskDir: dir });
    // A repo nobody has a worktree for does not win over the one that exists.
    expect(await provider.provision(input({ workItem: workItem("elsewhere") }))).toEqual({ hostId: "local", cwd: join(dir, "only"), repo: "only", provider: "kepler" });
  });

  it("with no worktrees at all, reuses the parent workspace, then the task dir itself", async () => {
    const dir = await task({});
    const provider = new KeplerTaskWorkspaceProvider({ taskDir: dir });
    const parent = { hostId: "remote", cwd: "/elsewhere" };
    expect(await provider.provision(input({ parent }))).toBe(parent);
    expect(await provider.provision(input())).toEqual({ hostId: "local", cwd: dir, provider: "kepler" });
  });
});
