/** Read-only synthetic collector benchmark. No host sampling, daemon or transport. */
import { performance } from "node:perf_hooks";
import { HostResourceCollector, type HostResourceSources } from "./index.js";
export async function benchmarkHostResources(iterations = 250) {
  if (!Number.isSafeInteger(iterations) || iterations < 1 || iterations > 10_000)
    throw new Error("invalid benchmark iterations");
  let mono = 0,
    calls = 0,
    bytes = 0;
  const sources: HostResourceSources = {
    platform: "linux",
    read: async (path) => {
      calls++;
      const value = path.endsWith("boot_id")
        ? "10000000-0000-4000-8000-000000000002"
        : path.endsWith("meminfo")
          ? "MemTotal: 16000000 kB\nMemAvailable: 8000000 kB\nMemFree: 1000000 kB\nSwapTotal: 2000000 kB\nSwapFree: 1000000 kB"
          : path.endsWith("vmstat")
            ? `pswpin ${mono}\npswpout ${mono}`
            : `cpu ${mono + 100} 0 0 ${mono + 100} 0 0 0 0\ncpu0 ${mono + 100} 0 0 ${mono + 100} 0 0 0 0`;
      bytes += Buffer.byteLength(value);
      return value;
    },
    pageSize: async () => {
      calls++;
      return 4096;
    },
    cgroup: async () => {
      calls++;
      return {
        cpu: { effectiveCores: 2, quotaCores: 2, cpusetCores: 4, scope: "visible-cgroup-hierarchy" },
        memory: {
          limitBytes: 4_000_000_000,
          currentBytes: 1_000_000_000,
          headroomBytes: 3_000_000_000,
          scope: "visible-cgroup-hierarchy",
        },
      };
    },
    storage: async () => {
      calls++;
      return { totalBytes: 100_000_000_000, availableBytes: 50_000_000_000, device: "synthetic", backing: "disk" };
    },
  };
  const collector = new HostResourceCollector({
    daemonInstanceId: "10000000-0000-4000-8000-000000000001",
    sources,
    storagePaths: { store: "synthetic", workspace: "synthetic", temp: "synthetic" },
    clock: { monotonic: () => mono, wall: () => Date.parse("2026-10-04T12:00:00.000Z") + mono },
  });
  // Warm JIT/schema caches before measuring. Logical time controls the refresh gate.
  for (let i = 0; i < 20; i++) {
    await collector.snapshot();
    mono += 5000;
  }
  calls = 0;
  bytes = 0;
  const times: number[] = [],
    cachedTimes: number[] = [];
  const cpu = process.cpuUsage(),
    heap = process.memoryUsage().heapUsed;
  let maxSnapshotBytes = 0;
  for (let i = 0; i < iterations; i++) {
    const start = performance.now();
    const snapshot = await collector.snapshot();
    times.push(performance.now() - start);
    maxSnapshotBytes = Math.max(maxSnapshotBytes, Buffer.byteLength(JSON.stringify(snapshot)));
    const cachedStart = performance.now();
    await collector.snapshot();
    cachedTimes.push(performance.now() - cachedStart);
    mono += 5000;
  }
  const cpuUsed = process.cpuUsage(cpu);
  const distribution = (values: number[]) => {
    values.sort((a, b) => a - b);
    return {
      p50: values[Math.floor(values.length * 0.5)],
      p95: values[Math.min(values.length - 1, Math.floor(values.length * 0.95))],
      max: values.at(-1),
    };
  };
  return {
    kind: "synthetic-in-process",
    iterations,
    freshMs: distribution(times),
    cachedMs: distribution(cachedTimes),
    cpuMs: (cpuUsed.user + cpuUsed.system) / 1000,
    heapDeltaBytesWithoutForcedGc: process.memoryUsage().heapUsed - heap,
    maxSnapshotBytes,
    sourceCalls: calls,
    procSourceBytes: bytes,
    realHostAcceptance: "not-run",
  };
}

/** Actual thread/IPC overhead at the byte ceiling, with generated bytes and no host file reads. */
export async function benchmarkNativeResourceIo(iterations = 1_000) {
  if (!Number.isSafeInteger(iterations) || iterations < 1 || iterations > 10_000)
    throw new Error("invalid benchmark iterations");
  const { Worker } = await import("node:worker_threads");
  const { createNativeResourceIo } = await import("./native-io.js");
  const { HOST_RESOURCE_LIMITS } = await import("@orca/protocol");
  const io = createNativeResourceIo(
    [],
    () =>
      new Worker(
        `
    const { parentPort, workerData } = require("node:worker_threads");
    const bytes = new Uint8Array(workerData.bytes);
    parentPort.on("message", ({ id }) => parentPort.postMessage({ id, ok: true, value: bytes }));
  `,
        {
          eval: true,
          execArgv: [],
          workerData: { bytes: HOST_RESOURCE_LIMITS.sourceBytes },
          resourceLimits: { maxOldGenerationSizeMb: 16, maxYoungGenerationSizeMb: 4, stackSizeMb: 1 },
        },
      ),
  );
  // The production worker is unref'd, so this bounded benchmark deadline keeps its await alive.
  const deadline = setTimeout(() => io.close(), 30_000);
  const rssBefore = process.memoryUsage().rss;
  const cpuBefore = process.cpuUsage();
  let peakRss = rssBefore;
  const times: number[] = [];
  try {
    const start = performance.now();
    await io.read("/proc/stat");
    const coldThreadAndFirstReplyMs = performance.now() - start;
    for (let i = 0; i < iterations; i++) {
      const tick = performance.now();
      const bytes = await io.read("/proc/stat");
      if (bytes.length !== HOST_RESOURCE_LIMITS.sourceBytes) throw new Error("invalid benchmark response");
      times.push(performance.now() - tick);
      peakRss = Math.max(peakRss, process.memoryUsage().rss);
    }
    times.sort((a, b) => a - b);
    const cpu = process.cpuUsage(cpuBefore);
    return {
      kind: "synthetic-worker-ipc-no-filesystem",
      iterations,
      bytesPerReply: HOST_RESOURCE_LIMITS.sourceBytes,
      coldThreadAndFirstReplyMs,
      roundTripMs: {
        p50: times[Math.floor(iterations * 0.5)],
        p95: times[Math.min(iterations - 1, Math.floor(iterations * 0.95))],
        max: times.at(-1),
      },
      cpuMs: (cpu.user + cpu.system) / 1000,
      sampledRssGrowthBytes: peakRss - rssBefore,
      realHostAcceptance: "not-run",
    };
  } finally {
    clearTimeout(deadline);
    io.close();
  }
}
