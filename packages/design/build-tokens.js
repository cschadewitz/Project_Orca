#!/usr/bin/env node
/**
 * ORCA design system — token build.
 *
 *   pnpm run design:build            write css/tokens.css and src/tokens.ts
 *   pnpm run design:check            exit 1 if they are out of date (for CI)
 *
 * Inputs  (edit these):      tokens.json, semantics.json (next to this file)
 * Outputs (never edit):      css/tokens.css, src/tokens.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const read = (f) => JSON.parse(readFileSync(join(here, f), "utf8"));
const T = read("tokens.json");
const S = read("semantics.json");
const check = process.argv.includes("--check");

const BANNER = `/* GENERATED by packages/design/build-tokens.js from tokens.json — do not edit.\n   Change a value in tokens.json and run: pnpm run design:build */\n`;
const themes = T.color.themes.map((t) => t.id);
const [first, ...rest] = themes;

/* ---------- helpers ---------- */

const scalarFamilies = () =>
  Object.entries(T).filter(
    ([k, v]) => v && typeof v === "object" && Array.isArray(v.tokens) && !["color", "shadow"].includes(k),
  );

const perTheme = (token, theme) =>
  typeof token.value === "string" ? token.value : (token.value[theme] ?? token.value[first]);

const decls = (tokens, theme, indent = "  ") =>
  tokens.map((t) => `${indent}--${t.name}: ${perTheme(t, theme)};`).join("\n");

/* a token only needs re-declaring in a later theme if its value differs */
const differs = (t, theme) => perTheme(t, theme) !== perTheme(t, first);

/* ---------- tokens.css ---------- */

function buildCss() {
  const themed = [...T.color.tokens, ...(T.shadow?.tokens ?? [])];
  const out = [BANNER];

  /* Faces first: they are bundled, so `block` is right — a flash of fallback in a desktop
     app reads as a bug, and the files are local and small enough that the block is a frame. */
  for (const f of T.type.fonts ?? []) {
    out.push(
      `@font-face {\n  font-family: "${f.family}";\n  src: url("${f.file}") format("woff2");\n  font-weight: ${f.weight ?? 400};\n  font-style: ${f.style ?? "normal"};\n  font-display: block;\n}\n`,
    );
  }

  out.push(`:root,\n[data-theme="${first}"] {\n  color-scheme: ${first};\n${decls(themed, first)}\n}\n`);

  for (const theme of rest) {
    const changed = themed.filter((t) => differs(t, theme));
    const body = `  color-scheme: ${theme};\n${decls(changed, theme)}`;
    out.push(`[data-theme="${theme}"] {\n${body}\n}\n`);
    /* follow the OS unless a theme was chosen explicitly — `color-scheme` included, so native
       scrollbars and form controls match the OS theme even when nothing set the attribute */
    out.push(
      `@media (prefers-color-scheme: ${theme}) {\n  :root:not([data-theme="${first}"]) {\n    color-scheme: ${theme};\n${decls(changed, theme, "    ")}\n  }\n}\n`,
    );
  }

  const scalars = scalarFamilies()
    .map(([name, fam]) => `  /* ${name} */\n${decls(fam.tokens, first)}`)
    .join("\n");
  const fonts = Object.entries(T.type.families)
    .map(([k, v]) => `  --font-${k}: ${v};`)
    .join("\n");
  /* The scale reaches CSS as the `.orca-text-*` classes below; an element takes one and the
     style has a single definition. These two custom properties per style are for the rules
     that need a size without the rest of it — the shell root, a glyph sized off the scale —
     so those do not have to write the number out (#211). */
  const textVars = T.type.groups
    .flatMap((g) => g.styles)
    .map((s) => `  --text-${s.name}-size: ${s.fontSize};\n  --text-${s.name}-line-height: ${s.lineHeight};`)
    .join("\n");
  out.push(`:root {\n${scalars}\n  /* type */\n${fonts}\n${textVars}\n}\n`);

  for (const g of T.type.groups) {
    out.push(`/* ${g.name} */`);
    for (const s of g.styles) {
      const fam = s.family ?? g.family;
      const lines = [
        `  font-family: var(--font-${fam});`,
        `  font-size: ${s.fontSize};`,
        `  line-height: ${s.lineHeight};`,
        `  font-weight: ${s.fontWeight};`,
      ];
      if (s.letterSpacing) lines.push(`  letter-spacing: ${s.letterSpacing};`);
      if (s.fontStyle) lines.push(`  font-style: ${s.fontStyle};`);
      out.push(`.orca-text-${s.name} {\n${lines.join("\n")}\n}\n`);
    }
  }

  return out.join("\n");
}

/* ---------- tokens.ts ---------- */

const union = (keys) => keys.map((k) => `'${k}'`).join(" | ");
const quote = (s) => `'${String(s).replace(/'/g, "\\'")}'`;

/**
 * The four size tokens the workflow canvas does arithmetic with (#177). Named here rather
 * than guessed from a prefix, so adding a `node-*` token does not silently change what the
 * layout module is handed.
 */
const GRAPH_GEOMETRY = ["node-w", "node-h", "layer-gap", "rank-gap"];

/**
 * The size tokens a pane splitter does arithmetic with (#276). A drag is a pointer
 * coordinate minus another one, and neither a clamp nor an `aria-valuemin` can be written as
 * a `var()`, so these six are emitted as numbers for the same reason the four above are.
 */
const PANE_GEOMETRY = [
  "pane-step",
  "pane-min-sidebar",
  "pane-max-sidebar",
  "pane-min-side",
  "pane-max-side",
  "pane-min-stack",
];

/** One size token's value, or a hard failure — a missing geometry token must not emit NaN. */
function sizeValue(name, needs) {
  const token = T.size.tokens.find((t) => t.name === name);
  if (!token) throw new Error(`tokens.json has no size token ${name}, which ${needs} needs`);
  return token.value;
}

function buildTs() {
  const familyNames = Object.fromEntries(
    [["color", T.color], ...scalarFamilies()].map(([k, fam]) => [k, fam.tokens.map((t) => t.name)]),
  );

  const raw = Object.fromEntries(
    themes.map((theme) => [
      theme,
      Object.fromEntries([...T.color.tokens, ...(T.shadow?.tokens ?? [])].map((t) => [t.name, perTheme(t, theme)])),
    ]),
  );

  /* A semantics key is a design word, not an identifier: 'no-results' is the name the
     spec uses, so quote anything that is not a bare JS property name. */
  const key = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : quote(k));

  const presentation = (obj, withGlyph) =>
    Object.entries(obj)
      .map(([k, v]) => {
        const parts = [`word: ${quote(v.word)}`];
        if (withGlyph && v.glyph) parts.push(`glyph: ${quote(v.glyph)}`);
        if (v.fg) parts.push(`fg: 'var(--${v.fg})'`, `fgToken: ${quote(v.fg)}`);
        if (v.bg) parts.push(`bg: 'var(--${v.bg})'`, `bgToken: ${quote(v.bg)}`);
        if (v.writes) parts.push(`writes: ${quote(v.writes)}`);
        return `  ${key(k)}: { ${parts.join(", ")} },`;
      })
      .join("\n");

  return `${BANNER}
/** Every colour token name. Use \`v(name)\` rather than a literal. */
export type ColorToken = ${union(familyNames.color)};

export type SpacingToken = ${union(familyNames.spacing)};
export type RadiusToken = ${union(familyNames.radius)};
export type SizeToken = ${union(familyNames.size)};
export type BorderToken = ${union(familyNames.border)};
export type ShadowToken = ${union((T.shadow?.tokens ?? []).map((t) => t.name))};
export type DurationToken = ${union(familyNames.duration)};
export type EasingToken = ${union(familyNames.easing)};
export type OpacityToken = ${union(familyNames.opacity)};
export type BreakpointToken = ${union(familyNames.breakpoint)};
export type ZToken = ${union(familyNames.z)};
export type TextStyle = ${union(T.type.groups.flatMap((g) => g.styles.map((s) => s.name)))};

export type DesignToken =
  | ColorToken | SpacingToken | RadiusToken | SizeToken
  | BorderToken | ShadowToken | DurationToken | EasingToken | OpacityToken | BreakpointToken
  | ZToken;

/** \`v('status-failed')\` → \`'var(--status-failed)'\`. The only way to reference a token in JS. */
export const v = (token: DesignToken): string => \`var(--\${token})\`;

export type ThemeId = ${union(themes)};
export const THEMES: readonly ThemeId[] = [${themes.map(quote).join(", ")}] as const;

/**
 * Literal values per theme. Only for contexts where a CSS variable cannot be
 * resolved — canvas 2D, an image export, a native menu. Prefer \`v()\` everywhere else.
 */
export const rawTokens: Record<ThemeId, Record<string, string>> = ${JSON.stringify(raw, null, 2)} as const;

/** Breakpoint thresholds in px, for \`matchMedia\` — a CSS media query cannot read a custom property. */
export const BREAKPOINTS: Record<BreakpointToken, number> = {
${T.breakpoint.tokens.map((t) => `  ${quote(t.name)}: ${Number.parseInt(t.value, 10)},`).join("\n")}
};

export type GraphGeometryToken = ${union(GRAPH_GEOMETRY)};

/**
 * The workflow canvas's box and gaps in px, for the same reason \`BREAKPOINTS\` is here: an
 * SVG path's \`d\` attribute and a node's \`x\`/\`y\` are arithmetic, and no \`var()\` can be
 * written inside either. The layout module takes these as an argument rather than reaching
 * for them, so the algorithm stays a plain module with a plain test.
 */
export const GRAPH_GEOMETRY: Record<GraphGeometryToken, number> = {
${GRAPH_GEOMETRY.map((name) => `  ${quote(name)}: ${Number.parseInt(sizeValue(name, "GRAPH_GEOMETRY"), 10)},`).join("\n")}
};

export type PaneGeometryToken = ${union(PANE_GEOMETRY)};

/**
 * The pane splitters' step and limits in px (#276). A drag is arithmetic on pointer
 * coordinates and a clamp is a comparison against a number, so — as with \`GRAPH_GEOMETRY\` —
 * no \`var()\` can be written where these are used. The boundary registry takes them as
 * values rather than reaching into the cascade, so clamping stays a plain function with a
 * plain test.
 */
export const PANE_GEOMETRY: Record<PaneGeometryToken, number> = {
${PANE_GEOMETRY.map((name) => `  ${quote(name)}: ${Number.parseInt(sizeValue(name, "PANE_GEOMETRY"), 10)},`).join("\n")}
};

export type RunStatus = ${union(Object.keys(S.runStatus))};
export const RUN_STATUSES: readonly RunStatus[] = [${Object.keys(S.runStatus).map(quote).join(", ")}] as const;

/** Word and glyph are not optional: status is never carried by colour alone. */
export const STATUS_PRESENTATION: Record<RunStatus, {
  word: string; glyph: string; fg: string; fgToken: ColorToken; bg: string; bgToken: ColorToken;
}> = {
${presentation(S.runStatus, true)}
};

export type ScheduleClass = ${union(Object.keys(S.scheduleClass))};
export const SCHEDULE_CLASSES: readonly ScheduleClass[] = [${Object.keys(S.scheduleClass).map(quote).join(", ")}] as const;
/** Word and glyph, like a run status: a classification is never carried by colour alone (rule 4). */
export const SCHEDULE_PRESENTATION: Record<ScheduleClass, {
  word: string; glyph: string; fg: string; fgToken: ColorToken; bg: string; bgToken: ColorToken;
}> = {
${presentation(S.scheduleClass, true)}
};

export type WorkItemStatus = ${union(Object.keys(S.workItemStatus))};
export const WORK_ITEM_STATUSES: readonly WorkItemStatus[] = [${Object.keys(S.workItemStatus).map(quote).join(", ")}] as const;
/**
 * A plan work item's own stored status — not a run status and not a schedule
 * classification. The classification is where the scheduler *put* the item; this is what
 * the item says about itself, and the schedule table draws both because they answer
 * different questions.
 *
 * Word and glyph, and deliberately no \`fg\` or \`bg\`: the eight tinted chips mean a run
 * status and nothing else, so this is drawn as a plain \`Chip\` and colour is not one of its
 * channels at all. The glyphs are reused from the run statuses and schedule classes that
 * mean the same thing, so nothing new goes into the symbol faces.
 */
export const WORK_ITEM_STATUS_PRESENTATION: Record<WorkItemStatus, {
  word: string; glyph: string;
}> = {
${presentation(S.workItemStatus, true)}
};

export type ConnectionState = ${union(Object.keys(S.connectionState))};
export const CONNECTION_PRESENTATION: Record<ConnectionState, {
  word: string; glyph: string; fg: string; fgToken: ColorToken; writes: string;
}> = {
${presentation(S.connectionState, true)}
};

export type AgentHealth = ${union(Object.keys(S.agentHealth))};
export const AGENT_HEALTH_STATES: readonly AgentHealth[] = [${Object.keys(S.agentHealth).map(quote).join(", ")}] as const;
/**
 * An agent's handshake health. \`unknown\` is first because it is the honest default: health
 * is tracked in the daemon's process and never persisted, so a freshly started daemon knows
 * nothing about an agent until it contacts one (#222). Word and glyph are not optional —
 * a degraded agent is never carried by an amber border alone.
 */
export const AGENT_HEALTH_PRESENTATION: Record<AgentHealth, {
  word: string; glyph: string; fg: string; fgToken: ColorToken;
}> = {
${presentation(S.agentHealth, true)}
};

export type StateViewKind = ${union(Object.keys(S.stateView))};
export const STATE_VIEW_KINDS: readonly StateViewKind[] = [${Object.keys(S.stateView).map(quote).join(", ")}] as const;
/** The word is the accessible name of the view; 'loading' has no glyph because it draws skeletons. */
export const STATE_VIEW_PRESENTATION: Record<StateViewKind, {
  word: string; glyph?: string; fg: string; fgToken: ColorToken;
}> = {
${presentation(S.stateView, true)}
};

export type SurfaceId = ${union(Object.keys(S.surface))};
export const SURFACE_IDS: readonly SurfaceId[] = [${Object.keys(S.surface).map(quote).join(", ")}] as const;
/**
 * The five top-level surfaces, in sidebar order (docs/design/10-information-architecture.md).
 * Word and glyph are not optional: below the sidebar breakpoint the label is hidden and the
 * glyph is the whole of the navigation, so the word stays on as the accessible name (#261).
 */
export const SURFACE_PRESENTATION: Record<SurfaceId, { word: string; glyph: string }> = {
${presentation(S.surface, true)}
};

/** Glyphs the chrome renders that are not a state: the crumb separator and the command key. */
export type ChromeGlyph = ${union(Object.keys(S.chrome))};
export const CHROME_GLYPHS: Record<ChromeGlyph, string> = {
${Object.entries(S.chrome)
  .map(([k, g]) => `  ${key(k)}: ${quote(g.glyph)},`)
  .join("\n")}
};

export type DependencyKind = ${union(Object.keys(S.dependencyKind))};
export type DependencyState = ${union(Object.keys(S.dependencyState))};
/** Kind is the stroke style, state is the stroke colour — neither is carried by colour alone. */
export const DEPENDENCY_STROKE: Record<DependencyKind, string> = ${JSON.stringify(S.dependencyKind, null, 2)} as const;
export const DEPENDENCY_COLOR: Record<DependencyState, string> = {
${Object.entries(S.dependencyState)
  .map(([k, t]) => `  ${k}: 'var(--${t})',`)
  .join("\n")}
};

export type Density = ${union(Object.keys(S.density))};
export const DENSITY_ROW_TOKEN: Record<Density, SizeToken> = {
${Object.entries(S.density)
  .map(([k, t]) => `  ${k}: '${t}',`)
  .join("\n")}
};
`;
}

/* ---------- write or check ---------- */

const outputs = [
  ["css/tokens.css", buildCss()],
  ["src/tokens.ts", buildTs()],
];

let stale = false;
for (const [name, content] of outputs) {
  const path = join(here, name);
  if (check) {
    let current = "";
    try {
      current = readFileSync(path, "utf8");
    } catch {
      /* a missing output is stale by definition */
    }
    if (current !== content) {
      stale = true;
      console.error(`packages/design/${name} is out of date — run: pnpm run design:build`);
    }
  } else {
    writeFileSync(path, content);
    console.log(`packages/design/${name}  ${content.length.toLocaleString()} bytes`);
  }
}
if (check && stale) process.exit(1);
if (check) console.log("design tokens are up to date");
